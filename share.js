function shareWeChat() {
    const url = window.location.href;
    if (navigator.clipboard) {
        navigator.clipboard.writeText(url).then(() => {
            showCopiedToast('Link copied! Paste it in WeChat to share.');
        });
    } else {
        prompt('Copy this link to share on WeChat:', url);
    }
}

function copyPoemLink() {
    const url = window.location.href;
    if (navigator.clipboard) {
        navigator.clipboard.writeText(url).then(() => {
            showCopiedToast('Link copied to clipboard!');
        });
    } else {
        const input = document.createElement('input');
        input.value = url;
        document.body.appendChild(input);
        input.select();
        document.execCommand('copy');
        document.body.removeChild(input);
        showCopiedToast('Link copied to clipboard!');
    }
}

function showCopiedToast(message) {
    let toast = document.querySelector('.copied-toast');
    if (!toast) {
        toast = document.createElement('div');
        toast.className = 'copied-toast';
        document.body.appendChild(toast);
    }
    toast.textContent = message;
    toast.classList.add('show');
    setTimeout(() => toast.classList.remove('show'), 2500);
}

